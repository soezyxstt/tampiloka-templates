import { readFile, mkdir, writeFile, rename } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { buildPublicCatalog } from '../packages/registry/src/public-catalog.mjs';
import { createCatalogWorker } from '../packages/registry/src/catalog-worker.mjs';

const registry = JSON.parse(await readFile(new URL('../packages/registry/templates.json', import.meta.url), 'utf8'));
const source = JSON.parse(await readFile(new URL('../packages/registry/public-demos.json', import.meta.url), 'utf8'));
const epoch = process.env.SOURCE_DATE_EPOCH;
if (epoch !== undefined && !/^\d+$/.test(epoch)) throw new Error('SOURCE_DATE_EPOCH must be a Unix timestamp.');
const catalog = buildPublicCatalog(registry, source, epoch === undefined ? {} : { updatedAt: new Date(Number(epoch) * 1000).toISOString() });
// Never replace a working public feed with an accidental empty/partial publication.
if (catalog.entries.length === 0) throw new Error('No public ready demos; refusing to publish an empty catalog.');
const body = `${JSON.stringify(catalog, null, 2)}\n`;
const etag = `"${createHash('sha256').update(body).digest('hex')}"`;
const worker = `// Generated by scripts/build-public-catalog.mjs. Do not edit.\nconst body = ${JSON.stringify(body)};\nconst etag = ${JSON.stringify(etag)};\n${createCatalogWorker.toString()}\nexport default createCatalogWorker(body, etag);\n`;
const directory = new URL('../packages/registry/dist/', import.meta.url);
await mkdir(directory, { recursive: true });
for (const [name, content] of [['catalog.v1.json', body], ['catalog-worker.mjs', worker]]) {
  const target = new URL(name, directory);
  const temporary = new URL(`${name}.${process.pid}.tmp`, directory);
  await writeFile(temporary, content);
  await rename(temporary, target);
}
console.log(`Public catalog: ${catalog.entries.length} demos, ${catalog.families.length} families. Validated JSON and Worker ready.`);
