// Match only known system messages so customer and staff text is never translated implicitly.
export function localizeSystemMessage(message: string, language: 'id' | 'en'): string {
  if (language === 'id') return message;
  if (english[message]) return english[message];
  const patterns: Array<[RegExp, string]> = [
    [/^Menu (.+) sedang habis atau tidak tersedia\.$/, '$1 is sold out or unavailable.'],
    [/^Varian untuk (.+) tidak valid\.$/, 'The selected variant for $1 is invalid.'],
    [/^Pilihan tambahan untuk (.+) tidak valid atau sudah tidak tersedia\.$/, 'An add-on for $1 is invalid or no longer available.'],
    [/^Pilihan wajib "(.+)" pada (.+) belum lengkap\.$/, 'The required option "$1" for $2 is incomplete.'],
    [/^Pilihan "(.+)" pada (.+) melebihi batas maksimal \((\d+)\)\.$/, 'Option "$1" for $2 exceeds the maximum ($3).'],
    [/^Kode promo "(.+)" tidak ditemukan atau sudah tidak aktif\.$/, 'Promo code "$1" was not found or is no longer active.'],
    [/^Kuota promo "(.+)" telah habis\.$/, 'The usage limit for promotion "$1" has been reached.'],
    [/^Promo "(.+)" hanya berlaku untuk Member yang sudah masuk\.$/, 'Promotion "$1" is only available to signed-in members.'],
  ];
  for (const [pattern, translation] of patterns) if (pattern.test(message)) return message.replace(pattern, translation);
  return message;
}
