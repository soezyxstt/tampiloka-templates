let seedingPromise: Promise<void> | null = null;

export async function ensureSeeded(): Promise<void> {
  assertDemoRuntime();
  if (seedingPromise) {
    return seedingPromise;
  }
  seedingPromise = runSeedInternal().finally(() => {
    seedingPromise = null;
  });
  return seedingPromise;
}

